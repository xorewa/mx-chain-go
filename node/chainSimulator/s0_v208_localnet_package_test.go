// This NON_RUNNING package supports only the declared flags below. Reject
// additional real CLI overrides as well as unknown flags: otherwise validation
// of default config/genesis paths says nothing about the effective startup input.
func validateS0R3ArgumentShape(t *testing.T, process s0R3ProcessBinding) {
	t.Helper()
	allowed := []string{"-port", "-rest-api-interface", "-config", "-p2p-key-pem-file"}
	if process.Role == "validator" || process.Role == "observer" {
		allowed = append(allowed, "-validator-key-pem-file", "-sk-index", "-working-directory")
	} else {
		require.Equal(t, "seednode", process.Role)
	}
	if process.Role == "observer" {
		allowed = append(allowed, "-destination-shard-as-observer", "-operation-mode")
	}
	require.Len(t, process.Argv, 1+2*len(allowed), "exact bounded argv cardinality")
	seen := make(map[string]bool)
	for index := 1; index < len(process.Argv); index += 2 {
		flag := process.Argv[index]
		require.Contains(t, allowed, flag, "undeclared startup flag")
		require.False(t, seen[flag], "duplicate startup flag")
		seen[flag] = true
		require.NotEmpty(t, process.Argv[index+1], "empty startup value")
		require.False(t, strings.HasPrefix(process.Argv[index+1], "-"), "flag used as a value")
	}
}

func argumentValue(t *testing.T, arguments []string, name string) string {
	t.Helper()
	count := 0
	value := ""
	for index := 0; index < len(arguments); index++ {
		if arguments[index] == name {
			require.Less(t, index+1, len(arguments), "missing argument value: %s", name)
			count++
			value = arguments[index+1]
		}
	}
	require.Equal(t, 1, count, "argument must occur exactly once: %s", name)
	return value
}

// Validate with the same parsers and key decoders used by startup, not PEM labels
// or generated expectations alone. This is input validation, not a node launch.
func validateS0R3StartupInputs(t *testing.T, root string, cfg *config.Config, nodes config.NodesConfig, inv s0R3ProcessInventory) {
	t.Helper()
	economics, err := commonConfig.LoadEconomicsConfig(filepath.Join(root, "config/economics.toml"))
	require.NoError(t, err)
	address, err := commonFactory.NewPubkeyConverter(cfg.AddressPubkeyConverter)
	require.NoError(t, err)
	hasher, err := hashFactory.NewHasher(cfg.Hasher.Type)
	require.NoError(t, err)
	marshalizer, err := marshalFactory.NewMarshalizer(cfg.Marshalizer.Type)
	require.NoError(t, err)
	supply, ok := new(big.Int).SetString(economics.GlobalSettings.GenesisTotalSupply, 10)
	require.True(t, ok, "invalid genesis supply")
	require.Positive(t, supply.Sign())
	wallets := signing.NewKeyGenerator(ed25519.NewEd25519())
	_, err = parsing.NewAccountsParser(genesis.AccountsParserArgs{
		GenesisFilePath: filepath.Join(root, "config/genesis.json"), EntireSupply: supply,
		MinterAddress:   economics.GlobalSettings.GenesisMintingSenderAddress,
		PubkeyConverter: address, KeyGenerator: wallets, Hasher: hasher, Marshalizer: marshalizer,
	})
	require.NoError(t, err)
	contracts, err := parsing.NewSmartContractsParser(filepath.Join(root, "config/genesisSmartContracts.json"), address, wallets)
	require.NoError(t, err)
	require.Empty(t, contracts.InitialSmartContracts(), "this simulator-derived baseline fixture intentionally has no genesis contracts")

	bls := signing.NewKeyGenerator(mcl.NewSuiteBLS12())
	secp := signing.NewKeyGenerator(secp256k1.NewSecp256k1())
	ports, directories, peers := map[int]bool{}, map[string]bool{}, map[string]bool{}
	validators, observers := map[string]bool{}, map[string]bool{}
	for _, node := range nodes.InitialNodes {
		validators[node.PubKey] = true
	}
	for _, process := range append(append([]s0R3ProcessBinding{}, inv.Processes...), inv.SupportProcesses...) {
		cwd := filepath.Join(root, process.WorkingDirectory)
		require.Equal(t, strconv.Itoa(process.P2PPort), argumentValue(t, process.Argv, "-port"))
		require.Equal(t, "localhost:"+strconv.Itoa(process.APIPort), argumentValue(t, process.Argv, "-rest-api-interface"))
		for _, port := range []int{process.P2PPort, process.APIPort} {
			require.True(t, port > 0 && port <= 65535, "invalid port")
			require.False(t, ports[port], "API/P2P port collision")
			ports[port] = true
		}
		keyPath := filepath.Clean(filepath.Join(cwd, argumentValue(t, process.Argv, "-p2p-key-pem-file")))
		require.Equal(t, filepath.Join(root, process.P2PKeyFile), keyPath)
		privateBytes, err := commonConfig.GetSkBytesFromP2pKey(keyPath)
		require.NoError(t, err)
		// Missing files otherwise select random-key fallback at real startup.
		require.NotEmpty(t, privateBytes, "missing pinned P2P key")
		private, err := secp.PrivateKeyFromByteArray(privateBytes)
		require.NoError(t, err)
		peer, err := p2pFactory.NewP2PKeyConverter().ConvertPublicKeyToPeerID(private.GeneratePublic())
		require.NoError(t, err)
		_, label, err := core.LoadSkPkFromPemFile(keyPath, 0)
		require.NoError(t, err)
		require.Equal(t, peer.Pretty(), label, "P2P body/label mismatch")
		require.False(t, peers[label], "duplicate P2P identity")
		peers[label] = true
		if process.Role == "seednode" {
			continue
		}
		require.Equal(t, "config/config.toml", argumentValue(t, process.Argv, "-config"))
		require.Equal(t, process.KeyFile, argumentValue(t, process.Argv, "-validator-key-pem-file"))
		require.Equal(t, strconv.Itoa(process.KeyIndex), argumentValue(t, process.Argv, "-sk-index"))
		require.Equal(t, "runtime/"+process.ID, argumentValue(t, process.Argv, "-working-directory"))
		directory := filepath.Join(cwd, argumentValue(t, process.Argv, "-working-directory"))
		require.False(t, directories[directory], "duplicate database root")
		directories[directory] = true
		encoded, label, err := core.LoadSkPkFromPemFile(filepath.Join(cwd, process.KeyFile), process.KeyIndex)
		require.NoError(t, err)
		decoded, err := hex.DecodeString(string(encoded))
		require.NoError(t, err)
		blsPrivate, err := bls.PrivateKeyFromByteArray(decoded)
		require.NoError(t, err)
		public, err := blsPrivate.GeneratePublic().ToByteArray()
		require.NoError(t, err)
		require.Equal(t, hex.EncodeToString(public), label, "BLS body/label mismatch")
		if process.Role == "validator" {
			require.Equal(t, nodes.InitialNodes[process.KeyIndex].PubKey, label)
		} else {
			require.False(t, validators[label], "observer is genesis validator")
			require.Contains(t, []string{"meta", "0", "1", "2"}, process.Shard)
			require.False(t, observers[process.Shard], "duplicate observer shard")
			observers[process.Shard] = true
			destination := process.Shard
			if destination == "meta" {
				destination = "metachain"
			}
			require.Equal(t, destination, argumentValue(t, process.Argv, "-destination-shard-as-observer"))
			require.Equal(t, "db-lookup-extension", argumentValue(t, process.Argv, "-operation-mode"))
		}
	}
	require.Len(t, peers, 21)
	require.Len(t, ports, 42)
	require.Len(t, directories, 20)
	require.Len(t, observers, 4)
}

func pemBlockTypes(t *testing.T, path string) []string {
	data, err := os.ReadFile(path)
	require.NoError(t, err)
	types := make([]string, 0)
	for len(data) > 0 {
		block, rest := pem.Decode(data)
		require.NotNil(t, block)
		types = append(types, block.Type)
		data = rest
	}
	return types
}

