func runS0R3Simulator(t *testing.T) s0R3SimulatorSnapshot {
	// Deterministic-key overlay is intentionally not part of current source.

	simulator, err := NewChainSimulator(ArgsChainSimulator{
		BypassTxSignatureCheck:         true,
		BypassCreateBlockTimeCheck:     true,
		TempDir:                        t.TempDir(),
		PathToInitialConfig:            "../../cmd/node/config/",
		NumOfShards:                    3,
		RoundDurationInMillis:          6000,
		SupernovaRoundDurationInMillis: 600,
		RoundsPerEpoch:                 core.OptionalUint64{HasValue: true, Value: 20},
		SupernovaRoundsPerEpoch:        core.OptionalUint64{HasValue: true, Value: 40},
		ApiInterface:                   api.NewNoApiInterface(),
		MinNodesPerShard:               1,
		MetaChainMinNodes:              1,
		GenesisTimestamp:               1700000000,
	})
	require.NoError(t, err)
	defer simulator.Close()

	require.NoError(t, simulator.GenerateBlocks(12))

	snapshot := s0R3SimulatorSnapshot{
		TerminalNonces: make(map[uint32]uint64),
		TerminalRounds: make(map[uint32]uint64),
		StateRoots:     make(map[uint32]string),
	}
	for _, privateKey := range simulator.GetValidatorPrivateKeys() {
		publicKey, errPublic := privateKey.GeneratePublic().ToByteArray()
		require.NoError(t, errPublic)
		snapshot.ValidatorPublicKeys = append(snapshot.ValidatorPublicKeys, hex.EncodeToString(publicKey))
	}
	sort.Strings(snapshot.ValidatorPublicKeys)

	wallets := simulator.GetInitialWalletKeys()
	for _, wallet := range wallets.StakeWallets {
		snapshot.WalletPublicKeys = append(snapshot.WalletPublicKeys, hex.EncodeToString(wallet.Address.Bytes))
	}
	for _, wallet := range wallets.BalanceWallets {
		snapshot.WalletPublicKeys = append(snapshot.WalletPublicKeys, hex.EncodeToString(wallet.Address.Bytes))
	}
	sort.Strings(snapshot.WalletPublicKeys)

	for _, shardID := range []uint32{0, 1, 2, core.MetachainShardId} {
		chain := simulator.GetNodeHandler(shardID).GetChainHandler()
		header := chain.GetCurrentBlockHeader()
		require.NotNil(t, header)
		snapshot.TerminalNonces[shardID] = header.GetNonce()
		snapshot.TerminalRounds[shardID] = header.GetRound()
		snapshot.StateRoots[shardID] = hex.EncodeToString(chain.GetCurrentBlockRootHash())
	}

	return snapshot
}

