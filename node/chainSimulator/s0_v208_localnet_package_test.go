func TestS0R3WaitingPoolReassignment(t *testing.T) {
	root := os.Getenv("S0_R3_PACKAGE_ROOT")
	if root == "" {
		t.Skip("S0_R3_PACKAGE_ROOT is required for reassignment qualification")
	}
	setup := loadS0R3NodesSetup(t, root)
	initialEligible, initialWaiting := setup.InitialNodesInfo()
	convert := func(input map[uint32][]nodesCoordinator.GenesisNodeInfoHandler) map[uint32][]nodesCoordinator.Validator {
		result := make(map[uint32][]nodesCoordinator.Validator)
		for shard, list := range input {
			for i, node := range list {
				v, err := nodesCoordinator.NewValidator(node.PubKeyBytes(), 1, uint32(i))
				require.NoError(t, err)
				result[shard] = append(result[shard], v)
			}
		}
		return result
	}
	snapshot := func(input map[uint32][]nodesCoordinator.Validator) map[string]uint32 {
		result := make(map[string]uint32)
		for shard, list := range input {
			for _, v := range list {
				key := hex.EncodeToString(v.PubKey())
				require.NotContains(t, result, key)
				result[key] = shard
			}
		}
		return result
	}
	eligible, waiting := convert(initialEligible), convert(initialWaiting)
	cfg, err := commonConfig.LoadMainConfig(filepath.Join(root, "config/config.toml"))
	require.NoError(t, err)
	epochs, err := commonConfig.LoadEpochConfig(filepath.Join(root, "config/enableEpochs.toml"))
	require.NoError(t, err)
	handler, err := enablers.NewEnableEpochsHandler(epochs.EnableEpochs, &epochNotifier.EpochNotifierStub{})
	require.NoError(t, err)
	shuffler, err := nodesCoordinator.NewHashValidatorsShuffler(&nodesCoordinator.NodesShufflerArgs{ShuffleBetweenShards: true, MaxNodesEnableConfig: epochs.EnableEpochs.MaxNodesChangeEnableEpoch, EnableEpochs: epochs.EnableEpochs, EnableEpochsHandler: handler})
	require.NoError(t, err)
	movedTotal := 0
	for epoch := uint32(1); epoch <= 4; epoch++ {
		handler.EpochConfirmed(epoch, 0)
		params := cfg.GeneralSettings.ChainParametersByEpoch[0]
		for _, candidate := range cfg.GeneralSettings.ChainParametersByEpoch {
			if candidate.EnableEpoch <= epoch {
				params = candidate
			}
		}
		random := sha256.Sum256([]byte(fmt.Sprintf("S0-R3-offline-waiting-route/%d", epoch)))
		args := nodesCoordinator.ArgsUpdateNodes{ChainParameters: params, Eligible: eligible, Waiting: waiting, Rand: random[:], NbShards: 3, Epoch: epoch}
		first, err := shuffler.UpdateNodeLists(args)
		require.NoError(t, err)
		second, err := shuffler.UpdateNodeLists(args)
		require.NoError(t, err)
		require.Equal(t, snapshot(first.Eligible), snapshot(second.Eligible))
		require.Equal(t, snapshot(first.Waiting), snapshot(second.Waiting))
		before := snapshot(eligible)
		for k, v := range snapshot(waiting) {
			require.NotContains(t, before, k)
			before[k] = v
		}
		after := snapshot(first.Eligible)
		for k, v := range snapshot(first.Waiting) {
			require.NotContains(t, after, k)
			after[k] = v
		}
		require.Len(t, before, 16)
		require.Len(t, after, 16)
		moved := 0
		for key, shard := range before {
			target, ok := after[key]
			require.True(t, ok)
			if shard != target {
				moved++
			}
		}
		for _, shard := range []uint32{0, 1, 2, core.MetachainShardId} {
			require.Len(t, first.Eligible[shard], 3)
			require.Len(t, first.Waiting[shard], 1)
			require.Len(t, first.ShuffledOut[shard], 1)
		}
		movedTotal += moved
		t.Logf("OFFLINE_SHUFFLER epoch=%d validators=16 waiting=4 cross_shard_moves=%d", epoch, moved)
		eligible, waiting = first.Eligible, first.Waiting
	}
	require.Positive(t, movedTotal, "must demonstrate an actual source-shuffler reassignment route")
	// Independently retain the inherited no-waiting counterexample: no surplus means no validator can rotate.
	handler.EpochConfirmed(1, 0)
	original := convert(initialEligible)
	negative, err := shuffler.UpdateNodeLists(nodesCoordinator.ArgsUpdateNodes{ChainParameters: cfg.GeneralSettings.ChainParametersByEpoch[0], Eligible: original, Waiting: map[uint32][]nodesCoordinator.Validator{}, Rand: []byte("no waiting counterexample"), NbShards: 3, Epoch: 1})
	require.NoError(t, err)
	require.Equal(t, snapshot(original), snapshot(negative.Eligible))
	require.Empty(t, snapshot(negative.ShuffledOut))
}

// The canonical epoch producer and block API use this same V1/V3 root selection.
// This checks byte/anchor consistency only; the caller must separately establish
// provenance from the running generation and agreement of metachain witnesses.
func verifyS0R3EpochHeaderAnchors(metaRaw []byte, shardRaw map[uint32][]byte, epoch uint32, chainID string) error {
	marshalizer, err := marshalFactory.NewMarshalizer("gogo protobuf")
	if err != nil {
		return err
	}
	hasher, err := hashFactory.NewHasher("blake2b")
	if err != nil {
		return err
	}
	meta, err := process.UnmarshalMetaHeader(marshalizer, metaRaw)
	if err != nil {
		return err
	}
	if meta.GetEpoch() != epoch || !meta.IsStartOfEpochBlock() || string(meta.GetChainID()) != chainID {
		return fmt.Errorf("wrong epoch, chain or non-epoch header")
	}
	anchors := meta.GetEpochStartHandler().GetLastFinalizedHeaderHandlers()
	if len(anchors) != 3 || len(shardRaw) != 3 {
		return fmt.Errorf("three shard anchors and bodies required")
	}
	seen := map[uint32]bool{}
	for _, anchor := range anchors {
		id := anchor.GetShardID()
		if id > 2 || seen[id] {
			return fmt.Errorf("invalid or duplicate shard anchor")
		}
		seen[id] = true
		raw, exists := shardRaw[id]
		if !exists || len(raw) == 0 {
			return fmt.Errorf("missing shard bytes")
		}
		if !bytes.Equal(hasher.Compute(string(raw)), anchor.GetHeaderHash()) {
			return fmt.Errorf("shard header hash mismatch")
		}
		header, err := process.UnmarshalShardHeader(marshalizer, raw)
		if err != nil {
			return err
		}
		if header.GetShardID() != id || header.GetNonce() != anchor.GetNonce() || header.GetRound() != anchor.GetRound() || header.GetEpoch() != anchor.GetEpoch() || string(header.GetChainID()) != chainID {
			return fmt.Errorf("shard header identity mismatch")
		}
		root := header.GetRootHash()
		if header.IsHeaderV3() {
			last, ok := header.GetLastExecutionResultHandler().(data.LastShardExecutionResultHandler)
			if !ok || last == nil || last.IsInterfaceNil() || last.GetExecutionResultHandler() == nil || last.GetExecutionResultHandler().IsInterfaceNil() {
				return fmt.Errorf("missing V3 execution result")
			}
			root = last.GetExecutionResultHandler().GetRootHash()
		}
		if len(root) != 32 || !bytes.Equal(root, anchor.GetRootHash()) {
			return fmt.Errorf("finalized state root mismatch")
		}
	}
	return nil
}

func TestS0R3EpochHeaderAnchorContracts(t *testing.T) {
	// Fixtures are native upstream DTOs encoded by the pinned upstream marshaler.
	// Negative controls alter the independent raw-header/epoch-anchor boundary.
	marshalizer, err := marshalFactory.NewMarshalizer("gogo protobuf")
	require.NoError(t, err)
	hasher, err := hashFactory.NewHasher("blake2b")
	require.NoError(t, err)
	for _, version := range []int{1, 3} {
		t.Run(fmt.Sprintf("V%d", version), func(t *testing.T) {
			shards := map[uint32][]byte{}
			anchors := []block.EpochStartShardData{}
			epoch := uint32(1)
			if version == 3 {
				epoch = 3
			}
			for id := uint32(0); id < 3; id++ {
				root := bytes.Repeat([]byte{byte(id + 1)}, 32)
				var header data.HeaderHandler = &block.Header{ShardID: id, Epoch: epoch - 1, Nonce: 12, Round: 20, RootHash: root, ChainID: []byte("local-testnet")}
				if version == 3 {
					header = &block.HeaderV3{ShardID: id, Epoch: epoch - 1, Nonce: 12, Round: 20, ChainID: []byte("local-testnet"), LastExecutionResult: &block.ExecutionResultInfo{ExecutionResult: &block.BaseExecutionResult{RootHash: root, HeaderNonce: 11, HeaderRound: 19, HeaderEpoch: epoch - 1}}}
				}
				encoded, e := marshalizer.Marshal(header)
				require.NoError(t, e)
				shards[id] = encoded
				anchors = append(anchors, block.EpochStartShardData{ShardID: id, Epoch: epoch - 1, Nonce: 12, Round: 20, RootHash: root, HeaderHash: hasher.Compute(string(encoded))})
			}
			makeMeta := func(list []block.EpochStartShardData, requestedEpoch uint32, chain string) []byte {
				var meta data.MetaHeaderHandler = &block.MetaBlock{Epoch: requestedEpoch, Nonce: 40, Round: 60, ChainID: []byte(chain), EpochStart: block.EpochStart{LastFinalizedHeaders: list}}
				if version == 3 {
					meta = &block.MetaBlockV3{Epoch: requestedEpoch, Nonce: 40, Round: 60, ChainID: []byte(chain), EpochStart: block.EpochStart{LastFinalizedHeaders: list}, LastExecutionResult: &block.MetaExecutionResultInfo{ExecutionResult: &block.BaseMetaExecutionResult{BaseExecutionResult: &block.BaseExecutionResult{RootHash: bytes.Repeat([]byte{4}, 32)}}}}
				}
				raw, e := marshalizer.Marshal(meta)
				require.NoError(t, e)
				return raw
			}
			raw := makeMeta(anchors, epoch, "local-testnet")
			require.NoError(t, verifyS0R3EpochHeaderAnchors(raw, shards, epoch, "local-testnet"))
			if destination := os.Getenv("S0_R3_HEADER_FIXTURE_ROOT"); destination != "" {
				meta, e := process.UnmarshalMetaHeader(marshalizer, raw)
				require.NoError(t, e)
				payload, e := json.Marshal(struct {
					Epoch    uint32                 `json:"epoch"`
					Meta     []byte                 `json:"meta"`
					MetaJSON data.MetaHeaderHandler `json:"meta_json"`
					Shards   map[uint32][]byte      `json:"shards"`
				}{epoch, raw, meta, shards})
				require.NoError(t, e)
				file, e := os.OpenFile(filepath.Join(destination, fmt.Sprintf("V%d.json", version)), os.O_CREATE|os.O_EXCL|os.O_WRONLY, 0600)
				require.NoError(t, e)
				_, e = file.Write(payload)
				require.NoError(t, e)
				require.NoError(t, file.Close())
			}

			for _, kind := range []string{"wrong-root", "wrong-hash", "wrong-nonce", "wrong-round", "wrong-shard-epoch", "duplicate-shard", "missing-anchor", "wrong-chain", "wrong-meta-epoch", "missing-body", "mutated-body", "malformed-meta"} {
				t.Run(kind, func(t *testing.T) {
					copied := append([]block.EpochStartShardData{}, anchors...)
					bodies := map[uint32][]byte{}
					for k, v := range shards {
						bodies[k] = append([]byte{}, v...)
					}
					changedEpoch := epoch
					chain := "local-testnet"
					switch kind {
					case "wrong-root":
						copied[0].RootHash = bytes.Repeat([]byte{99}, 32)
					case "wrong-hash":
						copied[0].HeaderHash = bytes.Repeat([]byte{99}, 32)
					case "wrong-nonce":
						copied[0].Nonce++
					case "wrong-round":
						copied[0].Round++
					case "wrong-shard-epoch":
						copied[0].Epoch++
					case "duplicate-shard":
						copied[1].ShardID = 0
					case "missing-anchor":
						copied = copied[:2]
					case "wrong-chain":
						chain = "wrong-chain"
					case "wrong-meta-epoch":
						changedEpoch++
					case "missing-body":
						delete(bodies, 0)
					case "mutated-body":
						bodies[0][0] ^= 0xff
					}
					changed := makeMeta(copied, changedEpoch, chain)
					if kind == "malformed-meta" {
						changed = []byte{0xff}
					}
					require.Error(t, verifyS0R3EpochHeaderAnchors(changed, bodies, epoch, "local-testnet"))
				})
			}
		})
	}
}

func TestS0R3RetainedEpochHeaderAnchors(t *testing.T) {
	// Executed only read-only against a qx-capture-derived bundle, never a sender.
	path := os.Getenv("S0_R3_EPOCH_HEADER_BUNDLE")
	if path == "" {
		t.Skip("read-only runtime bundle not supplied")
	}
	var bundle struct {
		Epoch         uint32            `json:"epoch"`
		ChainID       string            `json:"chain_id"`
		MetaWitnesses [][]byte          `json:"meta_witnesses"`
		MetaJSON      json.RawMessage   `json:"meta_json"`
		ShardHeaders  map[uint32][]byte `json:"shard_headers"`
	}
	raw, err := os.ReadFile(path)
	require.NoError(t, err)
	require.NoError(t, json.Unmarshal(raw, &bundle))
	require.Len(t, bundle.MetaWitnesses, 3)
	require.NotEmpty(t, bundle.MetaWitnesses[0])
	for _, witness := range bundle.MetaWitnesses {
		require.Equal(t, bundle.MetaWitnesses[0], witness, "independent metachain responses disagree")
	}
	require.NoError(t, verifyS0R3EpochHeaderAnchors(bundle.MetaWitnesses[0], bundle.ShardHeaders, bundle.Epoch, bundle.ChainID))
	marshalizer, err := marshalFactory.NewMarshalizer("gogo protobuf")
	require.NoError(t, err)
	header, err := process.UnmarshalMetaHeader(marshalizer, bundle.MetaWitnesses[0])
	require.NoError(t, err)
	encoded, err := json.Marshal(header)
	require.NoError(t, err)
	require.JSONEq(t, string(encoded), string(bundle.MetaJSON), "raw and structured epoch header differ")

	t.Logf("S0_R3_EPOCH_HEADER_CONSISTENCY epoch=%d meta_witnesses=3 shard_anchors=3 bundle_sha256=%s", bundle.Epoch, fileSHA256(t, path))
}
