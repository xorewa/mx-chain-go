func writeDeterministicP2PKey(t *testing.T, path, identity string) string {
	digest := sha256.Sum256([]byte("S0-R3-P2P-KEY-v1/" + identity))
	keyGenerator := signing.NewKeyGenerator(secp256k1.NewSecp256k1())
	privateKey, err := keyGenerator.PrivateKeyFromByteArray(digest[:])
	require.NoError(t, err)
	privateBytes, err := privateKey.ToByteArray()
	require.NoError(t, err)
	peerID, err := p2pFactory.NewP2PKeyConverter().ConvertPublicKeyToPeerID(privateKey.GeneratePublic())
	require.NoError(t, err)
	file, err := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o600)
	require.NoError(t, err)
	// SaveSkToPemFile wraps its input verbatim; the real P2P loader hex-decodes it.
	require.NoError(t, core.SaveSkToPemFile(file, peerID.Pretty(), []byte(hex.EncodeToString(privateBytes))))
	require.NoError(t, file.Close())
	return peerID.Pretty()
}

func copyFile(t *testing.T, source, destination string, mode os.FileMode) {
	input, err := os.Open(source)
	require.NoError(t, err)
	defer input.Close()
	output, err := os.OpenFile(destination, os.O_WRONLY|os.O_CREATE|os.O_EXCL, mode)
	require.NoError(t, err)
	_, err = io.Copy(output, input)
	require.NoError(t, err)
	require.NoError(t, output.Close())
}

func fileSHA256(t *testing.T, path string) string {
	file, err := os.Open(path)
	require.NoError(t, err)
	defer file.Close()
	digest := sha256.New()
	_, err = io.Copy(digest, file)
	require.NoError(t, err)
	return hex.EncodeToString(digest.Sum(nil))
}

